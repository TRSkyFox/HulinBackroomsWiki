// OCR 固定錯字修正：只處理「已確認的形近字／簡繁過度轉換」，不改正常用字。
// 2026-10-29：從真實場次補上「隻／週／彆／朵」等錯誤。
export function fixOcrText(input) {
  return String(input || '')
    .replace(/(?<!老)闆/g, '板')              // 天花闆；保留老闆
    .replace(/特彆/g, '特別').replace(/彆的/g, '別的')
    .replace(/分彆/g, '分別').replace(/告彆/g, '告別').replace(/類彆/g, '類別')
    .replace(/隻有一/g, '只有一').replace(/隻好/g, '只好')
    .replace(/隻要/g, '只要').replace(/隻是/g, '只是').replace(/隻剩/g, '只剩')
    .replace(/四週/g, '四周').replace(/週圍/g, '周圍').replace(/週遭/g, '周遭')
    .replace(/全麵/g, '全面').replace(/麵闆/g, '面板')
    .replace(/無麵者/g, '無面者').replace(/潦浪者/g, '流浪者')
    .replace(/嘯鳴體/g, '嗡鳴體').replace(/嗡聲/g, '嗡鳴聲')
    .replace(/舞檯/g, '舞台').replace(/標簽/g, '標籤').replace(/鐵煉/g, '鐵鍊')
    .replace(/([一二三四五六七八九十])檯/g, '$1台')
    .replace(/翻椅子底(?!下)/g, '翻椅子底下')
    .replace(/了全關掉[，,]\s*好好[跹睡]一覺/g, '把燈全關掉，好好睡一覺')
    .replace(/把燈全關掉[·・,，]\s*好好睡一覺/g, '把燈全關掉，好好睡一覺')
    .replace(/^(?:可|感|著|看)?[著着].*?[幕].*?記下.*?(?:麵麵|畫面)$/g, '盯著螢幕，記下閃過的畫面')
    .replace(/^拔掉播頭$/g, '拔掉插頭')
    .replace(/^什麼都彆碰/g, '什麼都別碰')
    .replace(/^什麼都彆動/g, '什麼都別動')
    .replace(/^讓侖關上吧/g, '讓它關上吧')
    .replace(/^不妻進去/g, '不要進去')
    .replace(/^(?:曠口|曠口的装修材料|摄定门口的装修材料|曠口的裝修材料)$/g, '搬走門口的裝修材料')
    .replace(/^路，避開燈管密集的地方$/g, '繞路，避開燈管密集的地方')
    .replace(/^把眼淚$/g, '把眼淚擦掉')
    .replace(/^知巧$/g, '')
    .replace(/^照紙條說的.*彆碰它$/g, '照紙條說的，別碰它')
    .replace(/彆碰/g, '別碰')
    .replace(/^麵壁/g, '面壁')
    .replace(/朵貼/g, '耳朵貼')
    /* ── 2026-10-29 真實場次（backroom-20261029-125010）補的規則 ──
       只收「這個字不可能正常出現在這裡」的形近誤讀，避免傷到正常用字。 */
    .replace(/冂/g, '門')                       // 櫃冂 → 櫃門（冂 是部首，不會當字用）
    .replace(/不妻/g, '不要')                   // 不妻動 → 不要動
    .replace(/眶知難/g, '感知難度')              // 眶知難 12 → 感知難度 12
    .replace(/數到干/g, '數到十')
    .replace(/拉煉/g, '拉鍊')
    .replace(/木制/g, '木製')
    .replace(/屬于/g, '屬於')
    .replace(/隻(看|寫|写|能|用|差|有|好|要|是|剩)/g, '只$1')
    .replace(/(黑暗|全黑|陰暗|角落|霧|雾|風|风|雨|雪|水|光|夢|梦|鏡|镜|機器|机器)里/g, '$1裡');
}
