let TABLE = null;
let FREQ = null;

function loadTable() {
  if (TABLE) return TABLE;
  TABLE = [];
  const file = TABLE_CANDIDATES.find(p => fs.existsSync(p));
  if (!file) return TABLE;
  const isCJK = ch => { const c = ch.codePointAt(0); return c >= 0x3400 && c <= 0x9fff; };
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    if (!line || line.startsWith('#')) continue;
    const toks = line.trim().split(/\s+/);
    for (let i = 0; i + 1 < toks.length; i += 2) {
      const a = toks[i], b = toks[i + 1];
      if ([...a].length !== 1 || [...b].length !== 1) continue;
      if (!isCJK(a) || !isCJK(b) || a === b) continue;
      TABLE.push([a, b]);
    }
  }
  return TABLE;
}

function loadFreq() {
  if (FREQ) return FREQ;
  FREQ = {};
  try { FREQ = JSON.parse(fs.readFileSync(FREQ_FILE, 'utf8')).chars || {}; } catch { }
  return FREQ;
}

let CHAR_MAP = null;
function buildCharMap() {
  const freq = loadFreq();
  const map = new Map();
  for (const [a, b] of loadTable()) {
    if (KEEP_AS_IS.has(a) || KEEP_AS_IS.has(b)) continue;
    const fa = freq[a] || 0, fb = freq[b] || 0;
    let hant = null, hans = null;
    if (TRAD_MATE.has(a)) { hant = a; hans = b; }
    else if (TRAD_MATE.has(b)) { hant = b; hans = a; }
    /* 語料裡一次都沒出現過的字（罕用字、新事件才會遇到的字）。
       以前是 continue —— 等於直接放棄轉換，於是「阅讀」「丢棄」「闭」這種
       簡體就一路漏進正式 Wiki。對照表本身的方向是繁→簡，反過來就是簡→繁，
       直接相信它；真正有歧義的字都在上面的 KEEP_AS_IS，不會走到這一行。 */
    else if (!fa && !fb) { hant = a; hans = b; }
    else if (!fa && fb >= 3) { hant = b; hans = a; }      // b 真的在用 → b 是繁體
    else if (!fb && fa >= 3) { hant = a; hans = b; }
    else if (Math.max(fa, fb) >= 5 && Math.max(fa, fb) >= Math.min(fa, fb) * 5) {
      hant = fa > fb ? a : b; hans = fa > fb ? b : a;
    }
    else if (fa >= 3 && fb >= 3 && fa >= fb * 3) { hant = a; hans = b; }
    else if (fa >= 3 && fb >= 3 && fb >= fa * 3) { hant = b; hans = a; }
    /* 頻率低到判斷不出方向（1～2 次）、或兩邊相當的字。
       以前是 continue，於是「阅／闭／严」這種只出現一兩次的字永遠不轉，
       新事件只要用到冷門字就會漏簡體。歧義字都在 KEEP_AS_IS，
       走到這裡就相信對照表的方向。 */
    else { hant = a; hans = b; }
    if (KEEP_AS_IS.has(hans)) continue;
    const prev = map.get(hans);
    if (!prev || (freq[hant] || 0) > (freq[prev] || 0)) map.set(hans, hant);
  }
  for (const [hans, hant] of EXPLICIT) if (!KEEP_AS_IS.has(hans)) map.set(hans, hant);
  return map;
}

/* 回傳 { text, kept }；kept = 刻意保留、沒有自動轉的字。 */
export function convert(input) {
  let s = String(input == null ? '' : input);
  for (const [from, to] of WORDS) {
    if (s.includes(from)) s = s.split(from).join(to);
  }
  if (!CHAR_MAP) CHAR_MAP = buildCharMap();
  const kept = new Set();
  const out = Array.from(s).map(ch => {
    let m = CHAR_MAP.get(ch);
    if (!m && VARIANTS.has(ch)) m = VARIANTS.get(ch);
    if (m && m !== ch) return m;
    if (KEEP_AS_IS.has(ch)) kept.add(ch);
    return ch;
  }).join('');
  return { text: out, kept: [...kept] };
}

export function toHant(input) {
  const s = convert(input).text;
  // 單字轉換的已知過度轉換（遊戲固定詞）
  return fixOcrText(s.replace(/(?<!老)闆/g, '板')
    .replace(/製服/g, '制服').replace(/麵向/g, '面向').replace(/四麵/g, '四面')
    .replace(/上麵/g, '上面').replace(/下麵/g, '下面').replace(/前麵/g, '前面')
    .replace(/後麵/g, '後面').replace(/[裡裏]麵/g, '裡面').replace(/外麵/g, '外面')
    .replace(/對麵|麵對/g, '面對').replace(/一麵/g, '一面').replace(/片麵/g, '片面')
    .replace(/正麵/g, '正面').replace(/見麵/g, '見面').replace(/會麵/g, '會面')
    .replace(/當麵/g, '當面').replace(/迎麵/g, '迎面').replace(/背麵/g, '背面')
    .replace(/地麵/g, '地面').replace(/水麵/g, '水面').replace(/路麵/g, '路面')
    .replace(/表麵/g, '表面').replace(/畫麵/g, '畫面').replace(/場麵/g, '場面')
    .replace(/憨著氣/g, '憋著氣'));
}
export function explain(input) {
  const r = convert(input);
  return { ...r, tablePairs: loadTable().length, charMapSize: (CHAR_MAP || buildCharMap()).size };
}
