import { fixOcrText } from '../ocr-fix.mjs';
const cases = [
  ['隻有一盞燈', '只有一盞燈'],
  ['四週的空間', '四周的空間'],
  ['彆的地方', '別的地方'],
  ['朵貼在牆上', '耳朵貼在牆上'],
  ['天花闆', '天花板'],
  ['老闆', '老闆'],
  ['特彆', '特別'],
  ['小舞檯', '小舞台'],
  ['五檯電話', '五台電話'],
  ['標簽', '標籤'],
  ['翻椅子底', '翻椅子底下'],
  ['了全關掉，好好跹一覺', '把燈全關掉，好好睡一覺'],
  ['把燈全關掉·好好睡一覺', '把燈全關掉，好好睡一覺'],
  ['可著重幕。，記下閃過的麵麵', '盯著螢幕，記下閃過的畫面'],
  ['拔掉播頭', '拔掉插頭'],
  ['什麼都彆碰，離開', '什麼都別碰，離開'],
  ["照紙條說的 ' 彆碰它", '照紙條說的，別碰它'],
  ['讓侖關上吧', '讓它關上吧'],
  ['不妻進去', '不要進去'],
  ['把眼淚', '把眼淚擦掉'],
];
let bad = 0;
for (const [a, want] of cases) {
  const got = fixOcrText(a);
  if (got !== want) { bad++; console.error('FAIL', a, '=>', got, 'want', want); }
}
console.log(JSON.stringify({ ok: bad === 0, total: cases.length, failed: bad }, null, 2));
process.exit(bad ? 1 : 0);
